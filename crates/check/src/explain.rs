//! Long-form explanations for every diagnostic code.
//!
//! Each entry has an example that triggers the code and a corrected version.
//! A test checks both, so the explanations cannot drift from the checker.

pub struct Explanation {
    pub code: &'static str,
    pub title: &'static str,
    pub text: &'static str,
    /// Source that produces this diagnostic. Empty when no short example exists.
    pub bad: &'static str,
    /// The corrected source; produces no errors.
    pub good: &'static str,
}

pub fn explain(code: &str) -> Option<&'static Explanation> {
    let code = code.trim().to_ascii_uppercase();
    CODES.iter().find(|e| e.code == code)
}

